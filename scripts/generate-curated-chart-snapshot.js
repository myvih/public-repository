const { readFileSync, writeFileSync } = require("node:fs");
const { randomUUID } = require("node:crypto");
const { resolve } = require("node:path");

const SNAPSHOT_PATH = resolve("curated-chart-snapshot.json");
const MIN_DYNAMIC_CANDIDATES = 80;

function shuffle(items) {
  return items
    .map((item) => ({ item, sort: Math.random() }))
    .sort((left, right) => left.sort - right.sort)
    .map(({ item }) => item);
}

function readSnapshot() {
  return JSON.parse(readFileSync(SNAPSHOT_PATH, "utf8"));
}

function normalizeCandidate(candidate, index) {
  if (!candidate || typeof candidate !== "object") {
    throw new Error(`Candidate ${index + 1} is not an object.`);
  }

  const title = typeof candidate.title === "string" ? candidate.title.trim() : "";
  const artist = typeof candidate.artist === "string" ? candidate.artist.trim() : "";
  const category = typeof candidate.category === "string" ? candidate.category.trim() : "";
  const source = typeof candidate.source === "string" ? candidate.source.trim() : "curated-online-seed";
  const region = typeof candidate.region === "string" ? candidate.region.trim() : "GLOBAL";
  const styles = Array.isArray(candidate.styles)
    ? candidate.styles.filter((style) => typeof style === "string" && style.trim())
    : [];

  if (!title || !artist || !category || !styles.length) {
    throw new Error(`Candidate ${index + 1} is missing title, artist, category, or styles.`);
  }

  return {
    ...candidate,
    artist,
    category,
    rank: index + 1,
    region,
    source,
    styles,
    title,
  };
}

const previousSnapshot = readSnapshot();
const previousCandidates = Array.isArray(previousSnapshot.candidates) ? previousSnapshot.candidates : [];

if (previousCandidates.length < MIN_DYNAMIC_CANDIDATES) {
  throw new Error(
    `Need at least ${MIN_DYNAMIC_CANDIDATES} curated hot-track candidates; got ${previousCandidates.length}.`,
  );
}

const generatedAt = new Date().toISOString();
const batchId = `${generatedAt.replace(/[:.]/g, "-")}-curated-${randomUUID().slice(0, 8)}`;
const candidates = shuffle(previousCandidates).map(normalizeCandidate);

const nextSnapshot = {
  provider: "remote-json",
  source: "curated-chart-snapshot",
  sourceType: "live-online-dynamic",
  generatedAt,
  batchId,
  sourceName: "curated-chart-snapshot",
  sourceNotes: [
    "Generated by scheduled online updater from a curated seed list.",
    "This is a dynamic online batch, not a third-party real-time chart feed.",
    "Client still resolves previewUrl through iTunes Search at runtime.",
  ],
  candidates,
};

writeFileSync(SNAPSHOT_PATH, `${JSON.stringify(nextSnapshot, null, 2)}\n`);

console.log(`Generated ${candidates.length} candidates (${batchId}).`);
