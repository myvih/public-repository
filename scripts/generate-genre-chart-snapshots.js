function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function writeJson(path, value) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`);
}

function hashText(input) {
  return createHash("sha256").update(input).digest("hex");
}

function createSeededRandom(seedText) {
  let state = parseInt(hashText(seedText).slice(0, 8), 16) || 0x9e3779b9;
  return () => {
    state ^= state << 13;
    state ^= state >>> 17;
    state ^= state << 5;
    return (state >>> 0) / 0xffffffff;
  };
}

function seededShuffle(items, seedText) {
  const random = createSeededRandom(seedText);
  return items
    .map((item) => ({ item, sort: random() }))
    .sort((left, right) => left.sort - right.sort)
    .map(({ item }) => item);
}

function cleanString(value, fallback = "") {
  return typeof value === "string" && value.trim() ? value.trim() : fallback;
}

function cleanStringArray(value) {
  return Array.isArray(value)
    ? value.filter((item) => typeof item === "string" && item.trim()).map((item) => item.trim())
    : [];
}

function normalizeAliases(value) {
  return Array.isArray(value)
    ? value
        .filter(
          (alias) =>
            alias &&
            typeof alias === "object" &&
            typeof alias.title === "string" &&
            typeof alias.artist === "string" &&
            typeof alias.label === "string",
        )
        .map((alias) => ({
          artist: alias.artist.trim(),
          label: alias.label.trim(),
          title: alias.title.trim(),
        }))
        .filter((alias) => alias.artist && alias.label && alias.title)
    : [];
}

function parseIsoDateOnly(value) {
  if (typeof value !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(value.trim())) {
    return null;
  }

  const timestamp = Date.parse(`${value.trim()}T00:00:00.000Z`);

  return Number.isFinite(timestamp) ? timestamp : null;
}

function getReleaseWindowValidation(candidate, generatedAtMs) {
  const releaseDate = cleanString(candidate.releaseDate);
  const releaseDateMs = parseIsoDateOnly(releaseDate);

  if (!releaseDate || releaseDateMs === null) {
    return { valid: false, reason: "missing_or_invalid_releaseDate" };
  }

  if (releaseDateMs > generatedAtMs) {
    return { valid: false, reason: "releaseDate_after_generatedAt" };
  }

  const ageDays = (generatedAtMs - releaseDateMs) / (24 * 60 * 60 * 1000);

  if (ageDays > NEW_RELEASE_MAX_AGE_DAYS) {
    return { valid: false, reason: `releaseDate_outside_${NEW_RELEASE_MAX_AGE_DAYS}_days` };
  }

  return { releaseDate, valid: true };
}

function normalizeCandidate(candidate, index, genre, generatedAtMs) {
  if (!candidate || typeof candidate !== "object" || Array.isArray(candidate)) {
    throw new Error(`${genre.slug} seed candidate ${index + 1} must be an object.`);
  }

  const title = cleanString(candidate.title);
  const artist = cleanString(candidate.artist);
  const category = cleanString(candidate.category, genre.slug);
  const styles = cleanStringArray(candidate.styles);
  const region = cleanString(candidate.region, "GLOBAL");
  const source = cleanString(candidate.source, `${genre.slug}-curated-seed`);
  const sourceUrl = cleanString(candidate.sourceUrl);

  if (!title || !artist || !category || !styles.length || !region || !source) {
    throw new Error(`${genre.slug} seed candidate ${index + 1} is missing required fields.`);
  }

  const aliases = normalizeAliases(candidate.aliases);
  const releaseWindow = NEW_RELEASE_GENRES.has(genre.slug)
    ? getReleaseWindowValidation(candidate, generatedAtMs)
    : null;

  if (releaseWindow && !releaseWindow.valid) {
    throw new Error(`${genre.slug} seed candidate ${index + 1} ${releaseWindow.reason}: ${artist} - ${title}.`);
  }

  const normalized = {
    rank: index + 1,
    title,
    artist,
    category,
    styles,
    region,
    source,
    ...(sourceUrl ? { sourceUrl } : {}),
    artistFacts: cleanStringArray(candidate.artistFacts),
    trackFacts: cleanStringArray(candidate.trackFacts),
    albumFacts: cleanStringArray(candidate.albumFacts),
    chartFacts: cleanStringArray(candidate.chartFacts),
    awardFacts: cleanStringArray(candidate.awardFacts),
    releaseContext: cleanStringArray(candidate.releaseContext),
    sourceNotes: cleanStringArray(candidate.sourceNotes),
    promoFacts: cleanStringArray(candidate.promoFacts),
    ...(releaseWindow?.releaseDate ? { releaseDate: releaseWindow.releaseDate } : {}),
    ...(releaseWindow?.releaseDate ? { releaseWindowDays: NEW_RELEASE_MAX_AGE_DAYS } : {}),
  };

  if (aliases.length) {
    normalized.aliases = aliases;
  }

  if (candidate.externalLinks && typeof candidate.externalLinks === "object" && !Array.isArray(candidate.externalLinks)) {
    const qqMusic = cleanString(candidate.externalLinks.qqMusic);
    if (qqMusic && qqMusic.startsWith("https://y.qq.com/")) {
      normalized.externalLinks = { qqMusic };
    }
  }

  return normalized;
}

async function buildChart(genre, generatedAt) {
  const generatedAtMs = Date.parse(generatedAt);
  const batchId = `${generatedAt.replace(/[:.]/g, "-")}-${genre.slug}-${randomUUID().slice(0, 8)}`;

  if (NEW_RELEASE_GENRES.has(genre.slug)) {
    const discovery = genre.slug === "mandopop-new-releases"
      ? await discoverMandopopNewReleases({ generatedAt, maxAgeDays: NEW_RELEASE_MAX_AGE_DAYS })
      : await discoverGlobalNewReleases({ generatedAt, maxAgeDays: NEW_RELEASE_MAX_AGE_DAYS });

    if (discovery.candidates.length < MIN_NEW_RELEASE_CANDIDATES) {
      throw new Error(
        `${genre.slug} automated discovery found ${discovery.candidates.length}/${MIN_NEW_RELEASE_CANDIDATES} valid new-release candidates. ` +
          `Every ${genre.slug} candidate must include releaseDate within ${NEW_RELEASE_MAX_AGE_DAYS} days of generatedAt.`,
      );
    }

    const candidates = discovery.candidates.map((candidate, index) => normalizeCandidate(candidate, index, genre, generatedAtMs));

    console.log(`${genre.slug} discovery summary: ${JSON.stringify(discovery.summary)}`);

    return {
      provider: "remote-json",
      sourceType: "live-online-dynamic",
      genre: genre.slug,
      generatedAt,
      batchId,
      sourceName: `tradio-${genre.slug}-discovery`,
      sourceNotes: NEW_RELEASE_SOURCE_NOTES,
      discoverySummary: discovery.summary,
      candidates,
    };
  }

  const seedPath = join(SEEDS_DIR, `${genre.slug}.seed.json`);
  const seed = readJson(seedPath);
  const seedCandidates = Array.isArray(seed.candidates) ? seed.candidates : [];

  if (seedCandidates.length < MIN_CANDIDATES) {
    throw new Error(`${genre.slug} seed must include at least ${MIN_CANDIDATES} candidates; got ${seedCandidates.length}.`);
  }

  const shuffled = seededShuffle(seedCandidates, `${genre.slug}:${batchId}`);
  const candidates = shuffled.map((candidate, index) => normalizeCandidate(candidate, index, genre, generatedAtMs));

  return {
    provider: "remote-json",
    sourceType: "live-online-dynamic",
    genre: genre.slug,
    generatedAt,
    batchId,
    sourceName: `tradio-${genre.slug}-curated-batch`,
    sourceNotes: SOURCE_NOTES,
    candidates,
  };
}

function assertNoUnexpectedSeedFiles() {
  const expected = new Set(GENRES.map((genre) => `${genre.slug}.seed.json`));
  const existing = readdirSync(SEEDS_DIR).filter((name) => name.endsWith(".seed.json"));
  const unexpected = existing.filter((name) => !expected.has(name));

  if (unexpected.length) {
    throw new Error(`Unexpected seed files: ${unexpected.join(", ")}`);
  }
}

async function main() {
  assertNoUnexpectedSeedFiles();

  const generatedAt = new Date().toISOString();
  const indexBatchId = `${generatedAt.replace(/[:.]/g, "-")}-genre-index-${randomUUID().slice(0, 8)}`;
  const genrePaths = {};
  const builtCharts = [];

  for (const genre of GENRES) {
    const chart = await buildChart(genre, generatedAt);
    const relativePath = `charts/${genre.slug}.json`;
    genrePaths[genre.slug] = relativePath;
    builtCharts.push({
      chart,
      genre,
      relativePath,
    });
  }
  mkdirSync(CHARTS_DIR, { recursive: true });

  for (const { chart, genre } of builtCharts) {
    const chartPath = join(CHARTS_DIR, `${genre.slug}.json`);
    writeJson(chartPath, chart);
  }

  const index = {
    provider: "remote-json",
    sourceType: "live-online-dynamic-index",
    generatedAt,
    batchId: indexBatchId,
    sourceName: "tradio-genre-chart-index",
    refreshCadence: "hourly",
    sourceNotes: SOURCE_NOTES,
    genres: genrePaths,
  };

  writeJson(INDEX_PATH, index);
  copyFileSync(join(CHARTS_DIR, "pop.json"), LEGACY_SNAPSHOT_PATH);

  console.log(`Generated ${GENRES.length} genre charts at ${generatedAt}.`);
  console.log(`Index batchId: ${indexBatchId}.`);
  console.log("Mirrored charts/pop.json to curated-chart-snapshot.json.");
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
